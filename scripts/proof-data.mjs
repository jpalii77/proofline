// The demo's measurement page (/proof) shows the same numbers as docs/accuracy.md and every claim of the
// last four fresh lists with its independent verdict. This builds public/proof-data.js from files already
// in the repository (accuracy.md, the run and verdict files, the gate labels); no network, no keys.
// A test fails when the page's data is out of step with those files.
//   node scripts/proof-data.mjs          -> exits 1 if public/proof-data.js is stale
//   node scripts/proof-data.mjs --write  -> writes it
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ACCURACY } from '../public/accuracy.js';
import { loadFinal } from './final-round.mjs';
import { accuracyRows, load as loadAblation } from './gate-ablation.mjs';
import { FRESH_ROUNDS, LAST_FRESH, load as loadReports, mark } from './report-impact.mjs';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = path.join(root, 'public', 'proof-data.js');
const REPO = 'https://github.com/jpalii77/proofline/blob/main/';

const readJson = (rel) => JSON.parse(fs.readFileSync(path.join(root, rel), 'utf8'));

/** Rows of the "With Tavily, without Tavily, and the model alone" table: label, kept right of checkable, sites found. */
export function searchRows(md) {
  const start = md.indexOf('## With Tavily, without Tavily, and the model alone');
  const end = md.indexOf('\n## ', start + 1);
  const rows = [];
  for (const line of md.slice(start, end).split('\n')) {
    const m = /^\| ([^|]+?) \| (?:(\d+) of (\d+)|0 claims) \| (\d+) of (\d+) \|/.exec(line);
    if (!m) continue;
    rows.push({ run: m[1].trim(), right: m[2] ? Number(m[2]) : 0, checkable: m[3] ? Number(m[3]) : 0, sitesFound: Number(m[4]), sites: Number(m[5]) });
  }
  return rows;
}

/** The values a claim sentence names, from its proof's parameters (for the Turkish wording on the page). */
function claimCtx(c) {
  const ctx = {};
  for (const e of c.evidence || []) {
    const p = e.params || {};
    ctx.domain ??= p.host || null;
    ctx.name ??= p.name || null;
    ctx.phone ??= p.phone || null;
  }
  return ctx;
}

/** Every business of one measured round: its kept claims with their verdicts, and what the gate dropped. */
export function roundClaims(run, verdicts, droppedLabels) {
  return run.results.map((x) => {
    const notes = verdicts.verdicts[x.id] || {};
    return {
      id: x.id,
      query: x.query,
      kept: (x.verified || []).map((c) => ({ type: c.type, tone: c.tone, statement: c.statement, ctx: claimCtx(c), mark: mark(notes[c.type]), note: String(notes[c.type] || '') })),
      dropped: droppedLabels.filter((d) => d.business === x.id).map((d) => {
        const c = (x.dropped || []).find((k) => k.type === d.type) || {};
        return { type: d.type, statement: c.statement || '', ctx: claimCtx(c), truth: d.truth, note: d.note };
      }),
    };
  });
}

export function build() {
  const md = fs.readFileSync(path.join(root, 'docs', 'accuracy.md'), 'utf8');
  const labels = readJson(path.join('eval', 'gate-ablation.json'));
  const ablation = loadAblation();
  const reports = loadReports();
  const rounds = accuracyRows(md).map((r) => ({ ...r, fresh: FRESH_ROUNDS.includes(r.round) }));
  const lists = LAST_FRESH.map((n) => {
    const l = labels.rounds.find((r) => r.round === n);
    const verdicts = readJson(l.verdicts);
    return { round: n, verdicts: REPO + l.verdicts, businesses: roundClaims(readJson(l.run), verdicts, l.dropped) };
  });
  return {
    headline: { rounds: ACCURACY.rounds, kept: ACCURACY.kept, total: ACCURACY.total },
    rounds,
    gate: { right: ablation.total.gate.right, wrong: ablation.total.gate.wrong, noGateRight: ablation.total.noGate.right, noGateWrong: ablation.total.noGate.wrong, removed: ablation.total.dropped.wrong, lost: ablation.total.dropped.right },
    reports: { lastFresh: pick(reports.lastFresh), all: pick(reports.all) },
    search: searchRows(md),
    lists,
    frozen: { file: REPO + 'eval/businesses-10.json', note: REPO + 'eval/FROZEN.md', sha256: /SHA-256: ([0-9a-f]{64})/.exec(fs.readFileSync(path.join(root, 'eval', 'FROZEN.md'), 'utf8'))[1], result: finalForPage(loadFinal()) },
    sources: { accuracy: REPO + 'docs/accuracy.md' },
  };
}

const pick = (t) => ({ reports: t.reports, withGate: t.withGate, withoutGate: t.withoutGate });
// The final round on the page: its numbers and GitHub links to the run and verdict files; null until checked.
export const finalForPage = (r) => r && { ...r, run: REPO + r.run, verdicts: REPO + r.verdicts };

export function render(data) {
  return `// Generated by scripts/proof-data.mjs from docs/accuracy.md and the run and verdict files. Do not edit by hand.\nexport const PROOF = ${JSON.stringify(data, null, 1)};\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = render(build());
  if (process.argv.includes('--write')) {
    fs.writeFileSync(OUT, text);
    console.log(`Written: ${path.relative(root, OUT)} (${text.length} bytes)`);
  } else if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== text) {
    console.error('public/proof-data.js is out of date: node scripts/proof-data.mjs --write');
    process.exit(1);
  } else console.log('Up to date.');
}
